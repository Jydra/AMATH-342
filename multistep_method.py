class Adams_Bashforth(MultistepMethod):
    def __new__(cls, steps: int):
        if steps < 1:
            raise ValueError("Steps cannot be less than 1")

        a = np.array([0] * (steps - 1) + [-1, 1])

        return MultistepMethod.from_a(a, is_explicit=True)
